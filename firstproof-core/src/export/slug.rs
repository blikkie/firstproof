/// Burns an unobtrusive, darkroom-authentic metadata proof slug onto an image buffer.
/// Positioned at the bottom margin with safe lab cutter inset (>= 35px at 300 DPI).
pub fn burn_proof_slug(img: &mut RgbImage, text: &str) {
    let img_w = img.width();
    let img_h = img.height();
    if img_w < 200 || img_h < 100 {
        return;
    }

    // Scale factor: on 1800x1200 or 1200x1800, scale = 2
    let scale: u32 = if img_w >= 1400 || img_h >= 1400 { 2 } else { 1 };
    let char_w = (GLYPH_WIDTH as u32) * scale;
    let char_h = (GLYPH_HEIGHT as u32) * scale;

    let chars: Vec<char> = text.chars().collect();
    let text_w = (chars.len() as u32) * char_w;
    let pad_x: u32 = 14 * scale;
    let pad_y: u32 = 6 * scale;
    let pill_w = (text_w + pad_x * 2).min(img_w - 40);
    let pill_h = char_h + pad_y * 2;

    // Bottom margin inset: safely clears 35px Printique guillotine blade bleed
    let bottom_margin = 35 * scale;
    let pill_y = img_h.saturating_sub(bottom_margin + pill_h);
    let pill_x = (img_w.saturating_sub(pill_w)) / 2;

    // Dark translucent pill background (dark charcoal [18, 18, 18], alpha ~0.82)
    let bg_color = [18u8, 18u8, 18u8];
    let alpha = 0.82f32;

    for y in pill_y..(pill_y + pill_h).min(img_h) {
        for x in pill_x..(pill_x + pill_w).min(img_w) {
            let p = img.get_pixel_mut(x, y);
            p[0] = ((1.0 - alpha) * (p[0] as f32) + alpha * (bg_color[0] as f32)) as u8;
            p[1] = ((1.0 - alpha) * (p[1] as f32) + alpha * (bg_color[1] as f32)) as u8;
            p[2] = ((1.0 - alpha) * (p[2] as f32) + alpha * (bg_color[2] as f32)) as u8;
        }
    }

    // Draw monospace text centered inside the pill
    let text_start_x = pill_x + (pill_w.saturating_sub(text_w)) / 2;
    let text_start_y = pill_y + pad_y;
    let text_color = Rgb([240u8, 240u8, 240u8]);

    for (i, &c) in chars.iter().enumerate() {
        let cx = text_start_x + (i as u32) * char_w;
        if cx + char_w > img_w {
            break;
        }
        let bitmap = get_glyph_bitmap(c);
        for row in 0..GLYPH_HEIGHT {
            let row_byte = bitmap[row];
            for col in 0..GLYPH_WIDTH {
                if (row_byte & (1 << (7 - col))) != 0 {
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let px = cx + (col as u32) * scale + dx;
                            let py = text_start_y + (row as u32) * scale + dy;
                            if px < img_w && py < img_h {
                                img.put_pixel(px, py, text_color);
                            }
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_burn_proof_slug() {
        let mut img = RgbImage::new(1800, 1200);
        burn_proof_slug(&mut img, "IMG_0730 • Rochester Cinema 500 • Luster • Grain: Off • First Proof v0.8.0");
        // Verify pixels in the pill are modified from pure black [0, 0, 0]
        let p = img.get_pixel(900, 1200 - 35 * 2 - 10);
        assert!(p[0] > 0 || p[1] > 0 || p[2] > 0);
    }
}
